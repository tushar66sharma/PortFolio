// Builds api/_lib/knowledge.js — the plain-text facts the chatbot answers from —
// out of src/constants.js and src/site.js. Vite's SSR loader resolves the image
// imports in constants.js, which plain Node cannot.
// Run: npm run knowledge (also runs before every build).
import { writeFileSync } from "node:fs";
import { fileURLToPath, pathToFileURL } from "node:url";
import { createServer } from "vite";

const ROOT = fileURLToPath(new URL("../..", import.meta.url));
const OUTPUT = new URL("../../api/_lib/knowledge.js", import.meta.url);
const HEADER = "// Generated by scripts/knowledge/build-knowledge.mjs — do not edit. Run: npm run knowledge";

export async function loadPortfolio() {
  const server = await createServer({
    root: ROOT,
    configFile: false,
    logLevel: "silent",
    server: { middlewareMode: true, hmr: false },
    appType: "custom",
  });
  try {
    const constants = await server.ssrLoadModule("/src/constants.js");
    const site = await server.ssrLoadModule("/src/site.js");
    return { constants, site };
  } finally {
    await server.close();
  }
}

function buildSections({ constants, site }) {
  const { SkillsInfo, experiences, projects, education } = constants;
  const current = experiences[0];

  const about = [
    "Name: Tushar Sharma",
    "Title: Software Engineer",
    `Current role: ${current.role} at ${current.company} (${current.date})`,
    `About: ${site.ABOUT_TEXT}`,
  ].join("\n");

  const experience = experiences
    .map((e) => [`- ${e.role} at ${e.company} (${e.date})`, `  ${e.desc}`, `  Skills: ${e.skills.join(", ")}`].join("\n"))
    .join("\n");

  // URLs sit at line ends so no punctuation sticks to them.
  const projectList = projects
    .map((p) =>
      [
        `- ${p.title.trim()}`,
        `  ${p.description.trim()}`,
        `  Tech: ${p.tags.map((t) => t.trim()).join(", ")}`,
        `  Source code: ${p.github}`,
        `  Live or demo link: ${p.webapp}`,
      ].join("\n")
    )
    .join("\n");

  const skills = SkillsInfo.map((g) => `${g.title}: ${g.skills.map((s) => s.name).join(", ")}`).join("\n");

  const educationList = education
    .map((e) => [`- ${e.degree}, ${e.school} (${e.date}), grade ${e.grade}`, `  ${e.desc}`].join("\n"))
    .join("\n");

  const contact = [
    "Visitors can message Tushar through the contact form on this website.",
    ...site.profiles.map((p) => `${p.platform} (${p.handle}): ${p.url}`),
    `${site.instagram.platform}: ${site.instagram.url}`,
    `Résumé (CV): ${site.RESUME_URL}`,
  ].join("\n");

  return { about, experience, projects: projectList, skills, education: educationList, contact };
}

export async function generateKnowledge() {
  const sections = buildSections(await loadPortfolio());
  const links = [...new Set(Object.values(sections).join("\n").match(/https?:\/\/\S+/g))];
  return [
    HEADER,
    `export const SECTIONS = ${JSON.stringify(sections, null, 2)};`,
    "",
    `export const LINKS = ${JSON.stringify(links, null, 2)};`,
    "",
  ].join("\n");
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  writeFileSync(OUTPUT, await generateKnowledge());
  console.log("wrote api/_lib/knowledge.js");
}
